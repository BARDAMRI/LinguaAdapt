const STORAGE_KEY_LANG = 'lingua_app_language';

const i18n = new I18n(translations);

function resolveDeviceLocale(): UiLanguage {
  const tag = Localization.getLocales()[0]?.languageTag?.toLowerCase() ?? 'en';
  return tag.startsWith('he') || tag.startsWith('iw') ? 'he' : 'en';
}

const deviceLocale = resolveDeviceLocale();
i18n.defaultLocale = 'en';
i18n.locale = deviceLocale;
i18n.enableFallback = true;

/** True when the UI is Hebrew. Read it at render time (it changes with the UI language). */
export let isRTL = deviceLocale === 'he';

// Our styles mirror the layout themselves; native mirroring would flip it twice.
I18nManager.allowRTL(false);
if (I18nManager.isRTL) I18nManager.forceRTL(false);

export function getUiLanguage(): UiLanguage {
  return isRTL ? 'he' : 'en';
}

/** Apply a new UI language at runtime. Call this before forcing a re-render. */
export function applyLocale(lang: string): void {
  const supported: UiLanguage = lang === 'he' ? 'he' : 'en';
  i18n.locale = supported;
  isRTL = supported === 'he';
}

/** Persist and apply the UI language saved earlier (call once before first render). */
export async function initLocaleFromStorage(): Promise<void> {
  try {
    const saved = await AsyncStorage.getItem(STORAGE_KEY_LANG);
    if (saved) applyLocale(saved);
  } catch {
    // ignore
  }
}

export function t(key: string, options?: object): string {
  return i18n.t(key, options);
}

export { i18n };
